// In a packaged app launched from Finder/Dock, process.cwd() may be "/" or a
// restricted directory. Many npm packages (dotenv, depd, body-parser, etc.)
// call process.cwd() at require-time and throw EPERM if the CWD is
// inaccessible. Point CWD to the user-data directory which always exists and
// is writable.
if (!app.isPackaged) {
  // Dev mode — keep natural CWD (repo root)
} else {
  try { process.cwd() } catch {
    const safe = app.getPath('userData')
    fs.mkdirSync(safe, { recursive: true })
    process.chdir(safe)
  }
}

// Single-instance lock — second launch focuses existing window instead of crashing on port conflict
if (!app.requestSingleInstanceLock()) {
  app.quit()
  process.exit(0)
}

const isDev = !app.isPackaged

